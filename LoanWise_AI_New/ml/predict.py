import os
import sys
import json
import numpy as np
import joblib

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.join(BASE_DIR, "model")
REPORTS_DIR = os.path.join(BASE_DIR, "reports")

FEATURE_COLUMNS = [
    "Age", "Monthly_Income", "Credit_Score", "Employment_Years",
    "Loan_Amount", "Loan_Tenure_Months", "Existing_Loans",
    "Existing_EMI", "Monthly_Expenses", "Previous_Defaults"
]


def get_risk_category(probability):
    if probability >= 0.75:
        return "Low Risk"
    elif probability >= 0.5:
        return "Medium Risk"
    elif probability >= 0.25:
        return "High Risk"
    else:
        return "Very High Risk"


def load_model():
    model_path = os.path.join(MODEL_DIR, "decision_tree_model.joblib")
    scaler_path = os.path.join(MODEL_DIR, "scaler.joblib")
    status_path = os.path.join(MODEL_DIR, "model_status.json")

    if not os.path.exists(model_path) or not os.path.exists(scaler_path):
        return None, None, {"error": "Model not found. Train the model first."}

    if os.path.exists(status_path):
        with open(status_path, "r") as f:
            status = json.load(f)
        if not status.get("trained", False):
            return None, None, {"error": "Model training was not completed successfully."}

    model = joblib.load(model_path)
    scaler = joblib.load(scaler_path)

    return model, scaler, None


def load_feature_importance():
    fi_path = os.path.join(REPORTS_DIR, "feature_importance.json")
    if os.path.exists(fi_path):
        with open(fi_path, "r") as f:
            return json.load(f)
    return None


def predict_single(input_data):
    model, scaler, error = load_model()
    if error:
        return {"success": False, "error": error["error"]}

    try:
        features = []
        for col in FEATURE_COLUMNS:
            val = input_data.get(col)
            if val is None:
                return {"success": False, "error": f"Missing required field: {col}"}
            try:
                features.append(float(val))
            except (ValueError, TypeError):
                return {"success": False, "error": f"Invalid value for {col}: {val}"}

        features_array = np.array([features])
        features_scaled = scaler.transform(features_array)

        prediction = int(model.predict(features_scaled)[0])
        probabilities = model.predict_proba(features_scaled)[0].tolist()
        approval_probability = probabilities[1] if len(probabilities) > 1 else probabilities[0]

        risk_category = get_risk_category(approval_probability)

        fi_data = load_feature_importance()
        feature_importance_info = []
        if fi_data and "sorted_features" in fi_data:
            feature_importance_info = fi_data["sorted_features"][:5]

        explanation_parts = []
        if prediction == 1:
            explanation_parts.append("The model predicts this loan application would likely be APPROVED based on the provided inputs.")
        else:
            explanation_parts.append("The model predicts this loan application would likely be REJECTED based on the provided inputs.")

        explanation_parts.append(f"The estimated approval probability is {approval_probability:.1%}.")
        explanation_parts.append(f"Risk assessment: {risk_category}.")

        if feature_importance_info:
            top_features = [f["feature"] for f in feature_importance_info[:3]]
            explanation_parts.append(
                f"The model's decisions are most influenced by: {', '.join(top_features)}. "
                "Note: This reflects patterns in the training data, not proven causal relationships."
            )

        explanation_parts.append(
            "IMPORTANT: This is an educational estimate from a Decision Tree model. "
            "It is not an actual bank decision and should not be treated as financial advice."
        )

        result = {
            "success": True,
            "prediction": prediction,
            "prediction_label": "Approved" if prediction == 1 else "Rejected",
            "approval_probability": round(approval_probability, 4),
            "rejection_probability": round(1 - approval_probability, 4),
            "risk_category": risk_category,
            "input_summary": {col: float(input_data[col]) for col in FEATURE_COLUMNS},
            "feature_importance": feature_importance_info,
            "explanation": " ".join(explanation_parts),
            "disclaimer": "This prediction is generated by a Decision Tree model trained on limited data. It is an educational estimate and does not represent an actual bank approval decision."
        }

        return result

    except Exception as e:
        return {"success": False, "error": f"Prediction failed: {str(e)}"}


def predict_batch(inputs_list):
    results = []
    for i, input_data in enumerate(inputs_list):
        result = predict_single(input_data)
        result["scenario_index"] = i
        results.append(result)
    return results


if __name__ == "__main__":
    try:
        input_text = sys.stdin.read()
        input_json = json.loads(input_text)

        if isinstance(input_json, list):
            results = predict_batch(input_json)
            output = {"success": True, "results": results}
        else:
            output = predict_single(input_json)

        print(json.dumps(output))

    except json.JSONDecodeError as e:
        print(json.dumps({"success": False, "error": f"Invalid JSON input: {str(e)}"}))
        sys.exit(1)
    except Exception as e:
        print(json.dumps({"success": False, "error": f"Unexpected error: {str(e)}"}))
        sys.exit(1)
